import type { Plugin } from "vite";

// Emits /sw.js at build time with every built file listed for precaching, so the app shell
// loads with zero network after the first visit. Same-origin GETs only: API traffic to the
// backend is never intercepted, so DDIL sync keeps its own retry/offline handling.
const PUBLIC_SHELL_FILES = ["/manifest.webmanifest", "/pwa-icon.svg", "/pwa-icon-192.png", "/pwa-icon-512.png", "/brand/rc_color.svg", "/brand/rc_split_color.svg"];

export function pwaShellPlugin(): Plugin {
  return {
    name: "tetherless-pwa-shell",
    apply: "build",
    generateBundle(_options, bundle) {
      const files = Object.keys(bundle).filter((name) => !name.endsWith(".map"));
      // Files from public/ are copied after generateBundle, so they are listed explicitly.
      const urls = ["/", ...files.map((name) => `/${name}`), ...PUBLIC_SHELL_FILES];
      // Hashed asset names already change with content; hashing contents too means a changed
      // index.html (unhashed) still busts the cache.
      const contents = files.map((name) => {
        const item = bundle[name];
        return name + (item.type === "chunk" ? item.code : String(item.source));
      });
      const cacheName = `tetherless-shell-${fnv1a(contents.join("\n"))}`;
      this.emitFile({ type: "asset", fileName: "sw.js", source: serviceWorkerSource(cacheName, urls) });
    },
  };
}

function serviceWorkerSource(cacheName: string, urls: string[]): string {
  return `// Generated by pwa-shell-plugin.ts — do not edit.
const CACHE = ${JSON.stringify(cacheName)};
const SHELL = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE && key.startsWith("tetherless-shell-")).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin) return;
  if (request.mode === "navigate") {
    event.respondWith(caches.match("/", { ignoreVary: true }).then((cached) => cached || fetch(request)));
    return;
  }
  event.respondWith(caches.match(request, { ignoreVary: true }).then((cached) => cached || fetch(request)));
});
`;
}

function fnv1a(text: string): string {
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return (hash >>> 0).toString(16).padStart(8, "0");
}
